import type { PptStudioSlide } from './types.js'

export function parseMarkdownSlides(titleInput: string, content?: string): PptStudioSlide[] {
  const title = String(titleInput ?? '').trim()
  const body = String(content ?? '').replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n').trim()

  const slides: PptStudioSlide[] = []

  // Cover
  slides.push({
    layout: 'cover',
    title,
    subtitle: extractSubtitle(body),
  })

  if (!body) {
    slides.push({
      layout: 'statement',
      title: title,
      subtitle: 'Generated by dsh-ppt-studio',
    })
    slides.push({
      layout: 'closing',
      title: 'Thank You',
    })
    return slides
  }

  // Remove YAML frontmatter
  const cleaned = body.replace(/^---[ \t]*\n[\s\S]*?\n---[ \t]*\n?/, '')
  const sections = splitSections(cleaned)

  for (const section of sections) {
    const slide = sectionToSlide(section)
    if (slide) slides.push(slide)
  }

  // Closing if not present
  const hasClosing = slides.some((s) => s.layout === 'closing')
  if (!hasClosing) {
    slides.push({
      layout: 'closing',
      title: 'Thank You',
    })
  }

  return slides
}

function extractSubtitle(body: string): string {
  const firstPara = body.split(/\n\s*\n/)[0] ?? ''
  if (!firstPara || firstPara.startsWith('#')) return ''
  return firstPara.slice(0, 160)
}

interface Section {
  heading: string
  level: number
  lines: string[]
}

function splitSections(text: string): Section[] {
  const lines = text.split('\n')
  const sections: Section[] = []
  let current: Section | null = null

  for (const raw of lines) {
    const line = raw.trimEnd()
    const headingMatch = /^(#{1,2})\s+(.+)$/.exec(line)
    if (headingMatch) {
      if (current) sections.push(current)
      current = { heading: headingMatch[2].trim(), level: headingMatch[1].length, lines: [] }
    } else if (current) {
      current.lines.push(line)
    } else if (line.trim()) {
      current = { heading: '', level: 0, lines: [line] }
    }
  }
  if (current) sections.push(current)
  return sections
}

function sectionToSlide(section: Section): PptStudioSlide | null {
  const heading = section.heading
  const bullets = section.lines
    .filter((l) => l.startsWith('- ') || l.startsWith('* ') || /^\d+\.\s/.test(l))
    .map((l) => l.replace(/^[-*\d.\s]+/, '').trim())
    .filter(Boolean)

  const paragraphs = section.lines
    .filter((l) => l && !l.startsWith('- ') && !l.startsWith('* ') && !/^\d+\.\s/.test(l) && !l.startsWith('#'))
    .map((l) => l.trim())
    .filter(Boolean)

  if (!heading && bullets.length === 0 && paragraphs.length === 0) return null

  if (!heading) {
    return {
      layout: 'statement',
      title: paragraphs[0] ?? bullets[0] ?? '',
      subtitle: paragraphs.slice(1).join(' ') || bullets.slice(1).join(' '),
    }
  }

  if (section.level === 1) {
    return {
      layout: 'section',
      title: heading,
      subtitle: paragraphs[0] || bullets[0] || '',
    }
  }

  if (bullets.length === 0 && paragraphs.length === 1 && paragraphs[0].length < 80) {
    return {
      layout: 'statement',
      title: heading,
      subtitle: paragraphs[0],
    }
  }

  return {
    layout: 'bullets',
    title: heading,
    bullets: bullets.length > 0 ? bullets : paragraphs,
  }
}
